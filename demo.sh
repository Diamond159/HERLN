#!/bin/bash

# ==============================================================================
# demo.sh
# 用于快速演示项目主流程。适合现场审查时使用。
# 演示模型在 ICEWS14s/WIKI 数据集上的基础训练过程，设置较少的 epoch 以便快速运行。
# ==============================================================================

echo "========================================================="
echo "开始快速演示项目主流程 (DRPM-NSCV / HERLN)"
echo "========================================================="

cd src || exit 1

# 使用 ICEWS14s 演示（相对 WIKI 如果更小些的话，或者按用户提供的 ICEWS14s 命令）
# 此处为了保证简洁稳定，运行一个 20 epoch 的轻量演示
echo ">>> 正在运行基础演示模型 (Dataset: ICEWS14s, Epochs: 20)..."
python main.py \
    -d ICEWS14s \
    --self-loop \
    --layer-norm \
    --weight 0.5 \
    --theta 1 \
    --relation-prediction \
    --relation-evaluation \
    --task-weight 0.0 \
    --gpu 0 \
    --freq-reg 5e-4 \
    --alpha 10 \
    --n-epochs 20 \
    --temporal-gating \
    --time-embedding-alpha 0.05

echo "========================================================="
echo "演示运行结束！可以通过查看 checkpoints 文件夹获取详细结果。"
echo "========================================================="
